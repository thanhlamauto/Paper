"""Crop only pixels already hidden by the main paper's original LaTeX trim.

Run with: uv run --python 3.12 --with pillow python scripts/prepare_main_gallery.py
The full grids remain the supplementary assets. No resize or lossy encoding is used.
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "figures/qualitative/lara_400k_cfg4"
OUT = ROOT / "figures/qualitative/main_gallery"
TRIM_BP = (539.0, 365.0, 7.0, 7.0)  # left, bottom, right, top in the old LaTeX


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    records = []
    trims = None
    for path in sorted(SOURCE.glob("sample_*.png")):
        with Image.open(path) as image:
            dpi = image.info.get("dpi", (72.0, 72.0))
            dx, dy = (72.0 / value for value in dpi)
            width, height = image.size
            left, bottom, right, top = TRIM_BP
            crop = (math.floor(left / dx), math.floor(top / dy),
                    math.ceil(width - right / dx), math.ceil(height - bottom / dy))
            remaining = (left - crop[0] * dx, bottom - (height - crop[3]) * dy,
                         right - (width - crop[2]) * dx, top - crop[1] * dy)
            rounded = tuple(round(value, 8) for value in remaining)
            if trims is None:
                trims = rounded
            elif trims != rounded:
                raise ValueError("Grid geometry differs; each file needs its own LaTeX trim")
            tile = image.crop(crop)
            # All source grids are opaque; remove only a redundant alpha channel.
            if tile.mode == "RGBA" and tile.getchannel("A").getextrema() == (255, 255):
                tile = tile.convert("RGB")
            output = OUT / path.name
            tile.save(output, optimize=True, dpi=dpi)
            with Image.open(output) as saved:
                if saved.convert("RGBA").tobytes() != image.crop(crop).convert("RGBA").tobytes():
                    raise ValueError(f"Pixel mismatch: {path.name}")
            records.append({"source": str(path.relative_to(ROOT)),
                            "output": str(output.relative_to(ROOT)),
                            "source_size": [width, height], "crop_box_px": crop,
                            "crop_size": list(tile.size), "dpi": dpi,
                            "source_bytes": path.stat().st_size,
                            "output_bytes": output.stat().st_size,
                            "rgba_pixel_sha256": hashlib.sha256(image.crop(crop).convert("RGBA").tobytes()).hexdigest()})
    if len(records) != 16:
        raise ValueError(f"Expected 16 gallery images, found {len(records)}")
    trim = " ".join(f"{value:.8f}bp" for value in trims)
    (OUT / "gallery.tex").write_text(
        "% Generated by scripts/prepare_main_gallery.py; preserve the original visible crop.\n"
        "\\def\\larathumb#1{\\includegraphics[width=0.121\\textwidth,trim=" + trim +
        ",clip]{figures/qualitative/main_gallery/sample_#1.png}}\n")
    (OUT / "manifest.json").write_text(json.dumps({"original_trim_bp": TRIM_BP,
        "residual_trim_bp": trims, "images": records}, indent=2) + "\n")
    before = sum(record["source_bytes"] for record in records)
    after = sum(record["output_bytes"] for record in records)
    print(f"16 pixel-identical crops: {before/1048576:.2f} -> {after/1048576:.2f} MiB")


if __name__ == "__main__":
    main()
